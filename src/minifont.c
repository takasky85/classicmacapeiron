/*
 * minifont.c - a 6x8 ASCII font built into the executable, and the few drawing calls that go
 * with it.
 *
 * The game's own fonts are Mac NFNT resources, which means they are artwork, which means they
 * arrive with the rest of the assets. The folder browser has to run *before* any of that exists,
 * so it cannot use them: something has to be able to put words on the screen when the only thing
 * loaded is the executable itself. Hence this - 95 glyphs, drawn by hand, under a kilobyte, and
 * nobody's property but this repository's.
 *
 * It writes straight into the frame buffer in palette indices, the same as everything else.
 */
