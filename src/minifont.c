#define GW 6
#define GH 8

int mini_text_width(const char *s)
{
    return (int)strlen(s) * GW;
}

void mini_char(int x, int y, char c, uint8_t ink)
{
    if (c < 32 || c > 126) c = '?';
    const unsigned char *g = glyphs[(int)c - 32];
    for (int row = 0; row < GH; row++) {
        int py = y + row;
        if (py < 0 || py >= SCREEN_H) continue;
        unsigned char bits = g[row];
        for (int col = 0; col < GW; col++) {
            if (!(bits & (0x80 >> col))) continue;
            int px = x + col;
            if (px < 0 || px >= SCREEN_W) continue;
            fb[py * SCREEN_W + px] = ink;
        }
    }
}

void mini_text(int x, int y, const char *s, uint8_t ink)
{
    for (; *s; s++, x += GW) mini_char(x, y, *s, ink);
}

/* The same, but every glyph twice the size - for the one line that has to be read across a room. */
void mini_text2x(int x, int y, const char *s, uint8_t ink)
{
    for (; *s; s++, x += GW * 2) {
        char c = *s;
        if (c < 32 || c > 126) c = '?';
        const unsigned char *g = glyphs[(int)c - 32];
        for (int row = 0; row < GH; row++)
            for (int col = 0; col < GW; col++) {
                if (!(g[row] & (0x80 >> col))) continue;
                for (int dy = 0; dy < 2; dy++)
                    for (int dx = 0; dx < 2; dx++) {
                        int px = x + col * 2 + dx, py = y + row * 2 + dy;
                        if (px >= 0 && py >= 0 && px < SCREEN_W && py < SCREEN_H)
                            fb[py * SCREEN_W + px] = ink;
                    }
            }
    }
}
