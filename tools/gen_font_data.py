#!/usr/bin/env python3
"""Bake the two free stand-in fonts into src/fontdata.c.

The in-game extractor (src/convert.c) has no TrueType renderer, so the Geneva and Chicago stand-ins
that tools/extract_assets.py draws with Pillow are drawn once, here, and compiled in as bitmaps:
one bit per pixel, in the strip layout the game's .bmp fonts use, plus the .fnt metrics text.
It also embeds the font credits and the Geneva 9.1 licence, which the game writes out beside the
artwork it makes (the OFL asks for that).

Run from the repository root after changing anything in tools/fonts:  python3 tools/gen_font_data.py
"""
import os, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import extract_assets as ea
from PIL import Image

FONTS = [('geneva9', 'Geneva9.1.otf', 10, 2), ('chicago12', 'pixChicago.ttf', 12, 3)]


def c_bytes(name, data):
    out = ['static const unsigned char %s[%d] = {' % (name, len(data))]
    for i in range(0, len(data), 16):
        out.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    out.append('};')
    return '\n'.join(out)


def main():
    parts = ['/* Generated by tools/gen_font_data.py - do not edit. */',
             '#include "apeiron.h"', '']
    tmp = tempfile.mkdtemp()
    table = []
    for stem, fname, asc, desc in FONTS:
        base = os.path.join(tmp, stem)
        W, H, _ = ea.ttf_to_font(os.path.join(HERE, 'fonts', fname), base, asc, desc)
        im = Image.open(base + '.bmp')
        assert im.size == (W, H)
        rb = (W + 7) // 8
        bits = bytearray(rb * H)
        px = im.load()
        for y in range(H):
            for x in range(W):
                if px[x, y]:
                    bits[y * rb + (x >> 3)] |= 0x80 >> (x & 7)
        fnt = open(base + '.fnt', 'rb').read()
        parts.append(c_bytes('bits_' + stem, bytes(bits)))
        parts.append(c_bytes('fnt_' + stem, fnt))
        table.append((stem, W, H, len(fnt)))
    parts.append(c_bytes('credits_txt', open(os.path.join(HERE, 'fonts', 'ATTRIBUTION.txt'), 'rb').read()))
    parts.append(c_bytes('ofl_txt', open(os.path.join(HERE, 'fonts', 'Geneva9.1-OFL.txt'), 'rb').read()))
    parts.append('')
    parts.append('const BakedFont baked_fonts[2] = {')
    for stem, W, H, n in table:
        parts.append('    { "font_%s", %d, %d, bits_%s, fnt_%s, %d },' % (stem, W, H, stem, stem, n))
    parts.append('};')
    parts.append('const unsigned char *baked_credits = credits_txt;')
    parts.append('const int baked_credits_len = (int)sizeof credits_txt;')
    parts.append('const unsigned char *baked_ofl = ofl_txt;')
    parts.append('const int baked_ofl_len = (int)sizeof ofl_txt;')
    open(os.path.join(HERE, '..', 'src', 'fontdata.c'), 'w').write('\n'.join(parts) + '\n')
    print('wrote src/fontdata.c', table)


if __name__ == '__main__':
    main()
